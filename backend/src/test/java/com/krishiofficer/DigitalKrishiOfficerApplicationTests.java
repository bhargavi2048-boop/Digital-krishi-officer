package com.krishiofficer;

import com.krishiofficer.dto.CropDto;
import com.krishiofficer.dto.FarmerDto;
import com.krishiofficer.service.CropService;
import com.krishiofficer.service.FarmerService;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;

import java.time.LocalDate;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * DigitalKrishiOfficerApplicationTests - JUnit 5 Unit & Integration Tests.
 * Demonstrates Object-Oriented Testing and Quality Verification.
 */
@SpringBootTest
class DigitalKrishiOfficerApplicationTests {

    @Autowired
    private FarmerService farmerService;

    @Autowired
    private CropService cropService;

    @Test
    @DisplayName("Verify Spring Boot application context loads successfully")
    void contextLoads() {
        assertNotNull(farmerService);
        assertNotNull(cropService);
    }

    @Test
    @DisplayName("OOP Test: Farmer registration encapsulates fields and returns valid DTO")
    void testFarmerRegistrationAndRetrieval() {
        FarmerDto newFarmer = new FarmerDto(
                null,
                "Ramesh Kumar",
                "9123456789",
                "Tamil Nadu",
                "Madurai",
                "Melur",
                "Chilli",
                2.0,
                "Black Cotton",
                "Borewell",
                "en"
        );

        FarmerDto saved = farmerService.registerOrUpdateFarmer(newFarmer);

        assertNotNull(saved.getId(), "Farmer ID should be generated by BaseEntity");
        assertEquals("Ramesh Kumar", saved.getFullName());
        assertEquals("Chilli", saved.getMainCrop());

        FarmerDto fetched = farmerService.getFarmerById(saved.getId());
        assertEquals("Madurai", fetched.getDistrict());
    }

    @Test
    @DisplayName("OOP Test: CropService properly creates and queries crops by farmer ID")
    void testCropLifecycleManagement() {
        CropDto crop = new CropDto(
                null,
                "Groundnut",
                "TMV 7",
                LocalDate.now(),
                LocalDate.now().plusDays(105),
                1.5,
                "Sandy Loam",
                "Sprinkler",
                "Germination",
                "Treated seeds with bio-fertilizer before sowing.",
                1L
        );

        CropDto saved = cropService.addCrop(crop);
        assertNotNull(saved.getId());
        assertEquals("Groundnut", saved.getName());

        List<CropDto> farmerCrops = cropService.getCropsByFarmer(1L);
        assertFalse(farmerCrops.isEmpty(), "Should retrieve crops associated with farmer ID 1");
    }
}
