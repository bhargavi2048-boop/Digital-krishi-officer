  /// Convenience method to share the full disease report via system share sheet
  Future<bool> shareDiseaseReport(DiseaseAnalysis analysis, String langCode) async {
    final text = formatDiseasePrescription(analysis, langCode);
    return await shareWithSystem(
      text,
      subject: 'Crop Health Report - ${analysis.cropName}',
    );
  }

  /// Directly launches WhatsApp with pre-filled message, or falls back to system share
  Future<bool> shareToWhatsApp(String text) async {
    final encodedText = Uri.encodeComponent(text);
    final whatsappUri = Uri.parse('whatsapp://send?text=$encodedText');
    final webWhatsappUri = Uri.parse('https://wa.me/?text=$encodedText');

    try {
      if (await canLaunchUrl(whatsappUri)) {
        return await launchUrl(whatsappUri, mode: LaunchMode.externalApplication);
      } else if (await canLaunchUrl(webWhatsappUri)) {
        return await launchUrl(webWhatsappUri, mode: LaunchMode.externalApplication);
      }
    } catch (_) {
      // Fallback below
    }

    // Fallback to system share sheet
    return await shareWithSystem(text, subject: 'Crop Advisory Report');
  }

  /// System share sheet for any app (Telegram, SMS, Email, Bluetooth, etc.)
  Future<bool> shareWithSystem(
    String text, {
    String? imagePath,
    String? subject,
  }) async {
    try {
      if (imagePath != null && imagePath.isNotEmpty && File(imagePath).existsSync()) {
        final xfile = XFile(imagePath);
        final result = await Share.shareXFiles(
          [xfile],
          text: text,
          subject: subject ?? 'Crop Prescription Slip',
        );
        return result.status == ShareResultStatus.success;
      } else {
        final result = await Share.share(
          text,
          subject: subject ?? 'Crop Prescription Slip',
        );
        return result.status == ShareResultStatus.success;
      }
    } catch (_) {
      return false;
    }
  }

  /// Copies text directly to the system clipboard
  Future<void> copyToClipboard(String text) async {
    await Clipboard.setData(ClipboardData(text: text));
  }
}
