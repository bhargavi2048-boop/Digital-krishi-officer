  /// Finds coordinates for city/district from local high-precision dictionary
  static Map<String, double>? lookupCoordinates(String locationName) {
    final clean = locationName.toLowerCase();

    // Check each known key
    for (final entry in knownCoordinates.entries) {
      if (clean.contains(entry.key)) {
        return entry.value;
      }
    }
    return null;
  }
